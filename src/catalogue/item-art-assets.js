import legacyRevolver from "../assets/item-revolver.webp";
import legacyFedora from "../assets/item-fedora.webp";
import legacyCoat from "../assets/item-coat.webp";
import legacyRing from "../assets/item-ring.webp";
import legacyMedical from "../assets/item-medical.webp";
import legacyBlade from "../assets/item-blade.webp";
import legacyGloves from "../assets/item-gloves.webp";
import legacyShoes from "../assets/item-shoes.webp";

// Every generated plate is a real bundled image. import.meta.glob keeps the
// registry auditable without hand-maintaining sixty hashed imports whenever a
// plate is regenerated by the art pipeline.
const GENERATED = import.meta.glob("../assets/items-v2/*.webp", {
  eager: true,
  import: "default",
  query: "?url",
});

const RARITIES = ["common", "uncommon", "rare", "epic", "legendary"];
const FALLBACK = Object.freeze({
  revolver: legacyRevolver,
  shotgun: legacyRevolver,
  pistol: legacyRevolver,
  blade: legacyBlade,
  knuckles: legacyGloves,
  fedora: legacyFedora,
  coat: legacyCoat,
  shoes: legacyShoes,
  ring: legacyRing,
  watch: legacyRing,
  medical: legacyMedical,
  tonic: legacyMedical,
});

const normalise = value => String(value || "")
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "");

const hash = value => [...String(value || "item")]
  .reduce((total, character, index) => (total * 31 + character.charCodeAt(0) + index) >>> 0, 7);

function rarityFor(item) {
  const value = normalise(item?.rarity || item?.rarity_key || item?.tier_name);
  return RARITIES.includes(value) ? value : "common";
}

function familyFor(item) {
  const fields = [
    item?.artKey,
    item?.art_key,
    item?.visualKey,
    item?.visual_key,
    item?.item_id,
    item?.itemId,
    item?.id,
    item?.name,
    item?.slot,
    item?.kind,
  ].map(normalise).join(" ");

  if (/revolver|peacemaker|service-revolver|harbor-iron/.test(fields)) return "revolver";
  if (/shotgun|scattergun|long-gun/.test(fields)) return "shotgun";
  if (/pistol|typewriter|sidearm/.test(fields)) return "pistol";
  if (/switchblade|stiletto|blade|knife|melee/.test(fields)) return "blade";
  if (/knuckle|glove|gauntlet|hand/.test(fields)) return "knuckles";
  if (/fedora|crown|helmet|headwear|hat/.test(fields)) return "fedora";
  if (/overcoat|coat|vest|armor|armour|body/.test(fields)) return "coat";
  if (/shoe|boot|oxford|foot/.test(fields)) return "shoes";
  if (/ring|signet|jewel|accessory/.test(fields)) return "ring";
  if (/watch|timepiece/.test(fields)) return "watch";
  if (/tonic|booster|elixir|potion/.test(fields)) return "tonic";
  if (/medical|first-aid|morphine|bandage|supply/.test(fields)) return "medical";
  if (normalise(item?.kind) === "weapon") return "pistol";
  if (normalise(item?.kind) === "armor") return "coat";
  if (normalise(item?.kind) === "accessory") return "ring";
  return "medical";
}

const generatedPath = (rarity, family) => `../assets/items-v2/${rarity}-${family}.webp`;

// The same item keeps the same illustration on the catalogue, inventory,
// equipment board and public character card. A deterministic variant token
// adds a restrained hue/texture treatment per item ID, so two items in one
// rarity/family never render as literal clones.
export function itemArtAsset(item) {
  const rarity = rarityFor(item);
  const family = familyFor(item);
  const key = `${rarity}-${family}`;
  const id = item?.item_id || item?.itemId || item?.id || item?.name || key;
  const seed = hash(id);
  const src = GENERATED[generatedPath(rarity, family)] || FALLBACK[family] || legacyMedical;
  return {
    src,
    key,
    family,
    rarity,
    variant: seed % 24,
    hue: (seed % 21) - 10,
    scale: 1 + (seed % 5) * 0.008,
  };
}

export const ITEM_ART_ASSETS = Object.freeze({ ...FALLBACK });
